    public static void main(String[] args) {

        // 콘솔로 입력받는 게임 Scanner 활용
        Scanner sc = new Scanner(System.in);

        Student student = new Student();

        // 메뉴가 나오기 전에 규칙 안내를 한 번만 출력한다.
        student.showRules();

        // 사용자가 입력할 수 있는 화면
        while (true) {
            //   1. 교수님 면담 / 2. 공부 / 3. 휴식 / 4. 상태 보기 / 9. 프로그램 종료
            System.out.println("=============연구실 생존기 메뉴=============");
            System.out.println("1. 교수님 면담");
            System.out.println("2. 공부");
            System.out.println("3. 휴식");
            System.out.println("4. 상태 보기");
            System.out.println("9. 프로그램 종료");
            System.out.println("=======================================");
            System.out.print("메뉴를 선택해주세요 : ");

            int no = sc.nextInt();

            switch (no) {
                case 1 :
                    System.out.println("1. 꼼꼼한 교수 / 2. 온화한 교수 / 0. 뒤로 가기");
                    System.out.print("교수님을 선택해주세요 : ");
                    int professorNo = sc.nextInt();
                    if (professorNo == 0) {
                        System.out.println("메뉴로 돌아갑니다");
                    } else {
                        student.talk(professorNo);
                    }
                    break;
                case 2 : student.study();
                    break;
                case 3 : student.rest();
                    break;
                case 4 : student.showStatus();
                    break;
                case 9 :
                    System.out.println("프로그램을 종료합니다");
                    break;
                default :
                    System.out.println("잘못된 번호 입력!");
                    break;
            }

            if (no == 9) {
                break;
            }

            if (student.isFinished()) {
                System.out.println("게임이 끝났습니다");
                break;
            }

        }

    }

